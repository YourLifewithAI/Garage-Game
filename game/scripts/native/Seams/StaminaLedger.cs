namespace GarageGame.Native.Seams;

// The ledger seam between the body and the kernel, fixed by the mechanics round's contract round (M0, 14 October 2026;
// contracts/README.md "The stamina ledger"). The integrator owns this file: the kernel (M1, game/scripts/native/Kernel/**)
// implements IStaminaLedger and binds it to SmallPlayerController.StaminaLedger; the body (M5, SmallPlayerController.cs) reports
// to it once a physics tick and obeys its gate. Neither edits the other's files, and a change here is a contract change.
// Both sides test against one fixture, contracts/examples/ledger/stamina_ledger.json (generated by
// contracts/examples/build_examples.py, checked against a reference model by contracts/tests).

/// <summary>
/// What the body did this physics tick that the stamina bar pays for, beyond climbing (which keeps
/// SmallPlayerController.ClimbBudget): seconds running on foot, seconds swimming in deep water at the surface, and seconds
/// under water. Raw seconds of this tick, each at least 0 and at most the tick, and at most one of them above 0 (a body is in
/// one of these at a time). The body never reads a rate, a price or a knack: the kernel charges the seconds from the island's
/// rules pack (traits.stamina) and the team's knacks (Long breath, Strong swimmer).
/// </summary>
public readonly record struct BodyExertion(float SprintS, float DeepWaterS, float DiveS)
{
    /// <summary>A tick that cost nothing beyond climbing.</summary>
    public static BodyExertion None => new(0f, 0f, 0f);
}

/// <summary>
/// The bar as the body must obey it after the tick. Empty: the bar is at zero, so a climb's grip fails (the body falls from
/// where it is, and the fall's rules decide the rest) and in deep water the body is taken back to shore. NoRun: the body
/// cannot run (sprint is ignored; the walk keeps its pace), from the moment the bar runs empty until the first bar, the top
/// row, refills to the pack's fraction of itself (traits.stamina.empty_no_run_until_fraction; the founder, 15 October:
/// completely). A floating body is never gated.
/// </summary>
public readonly record struct StaminaGate(bool Empty, bool NoRun)
{
    /// <summary>No ledger bound (fixture bodies, Creative, today's play): nothing is gated.</summary>
    public static StaminaGate Free => new(false, false);
}

/// <summary>
/// The kernel's stamina ledger, as the body sees it. Per physics tick the body calls Report once, before
/// SmallPlayerController.VitalsTick (which keeps the refill and the heal on standable ground), then reads Gate. The refill
/// never covers the seconds the tick reported as running.
/// </summary>
public interface IStaminaLedger
{
    void Report(BodyExertion exertion);
    StaminaGate Gate { get; }
}
